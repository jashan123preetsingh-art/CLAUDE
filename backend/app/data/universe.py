    metas: list[StockMeta] = []
    for sym, name, sector, mcap, fno in _SEED:
        metas.append(
            StockMeta(
                symbol=sym,
                name=name,
                exchange=Exchange.NSE,
                sector=sector,
                market_cap_cr=float(mcap),
                is_fno=fno,
                listed_days=1500,
            )
        )
    return metas
